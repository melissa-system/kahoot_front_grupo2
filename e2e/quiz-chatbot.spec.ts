import { expect, test } from '@playwright/test';

test('propuesta de chat: revisar, corregir, seleccionar y agregar una sola vez', async ({ page }, testInfo) => {
  await page.goto('/login');
  await page.getByLabel('Correo').fill('profe@profelink.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('profelink123');
  await page.getByRole('button', { name: 'Entrar' }).click();
  await page.getByRole('link', { name: 'Paradigmas: repaso rápido', exact: true }).click();
  const savedQuestions = page.locator('section[aria-labelledby="questions-title"] > ol > li');
  await expect(savedQuestions).toHaveCount(3);
  const before = await savedQuestions.count();
  await page.getByRole('button', { name: 'Chat bot' }).click();
  const chat = page.getByRole('dialog', { name: 'Chat bot · ProfeLink' });
  await expect(chat).toBeVisible();
  await expect(chat.getByText(/Modo simulado/)).toBeVisible();
  await expect(chat.getByLabel('Cantidad (opcional)')).toHaveCount(0);
  await chat.getByLabel('¿Qué preguntas necesitas?').fill('3 preguntas de ciencias para sexto grado');
  await chat.getByRole('button', { name: 'Enviar' }).click();
  await expect(chat.getByRole('button', { name: 'Ver propuesta' })).toHaveAttribute('aria-expanded', 'false');
  await expect(chat.getByLabel('Afirmación propuesta 1')).not.toBeVisible();
  await chat.getByRole('button', { name: 'Ver propuesta' }).click();
  await expect(chat.getByLabel('Afirmación propuesta 1')).toBeVisible();
  const preview = chat.getByRole('region', { name: 'Edición de la propuesta' });
  const previewBox = (await preview.boundingBox())!;
  expect(previewBox.height).toBeGreaterThan(testInfo.project.name === 'desktop' ? 400 : 280);
  if (testInfo.project.name === 'desktop') {
    expect(previewBox.width).toBeGreaterThan(500);
    expect(previewBox.x).toBeGreaterThan((await chat.getByRole('log').boundingBox())!.x);
  }
  const statement = chat.getByLabel('Afirmación propuesta 1');
  await expect(statement).toHaveAttribute('rows', '3');
  expect(await statement.evaluate((element) => Number.parseFloat(element.ownerDocument.defaultView!.getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16);
  await chat.getByLabel('Afirmación propuesta 1').fill('El Sol es una estrella: revisado por el profesor');
  await chat.getByRole('checkbox', { name: 'Incluir pregunta 3' }).uncheck();
  await chat.getByRole('button', { name: 'Pantalla completa' }).click();
  const restore = chat.getByRole('button', { name: 'Restaurar tamaño' });
  await expect(restore).toHaveAttribute('aria-pressed', 'true');
  await expect(restore).toBeFocused();
  const expanded = await chat.boundingBox();
  expect(expanded?.width).toBe(page.viewportSize()?.width);
  expect(expanded?.height).toBe(page.viewportSize()?.height);
  await expect(chat.getByLabel('Afirmación propuesta 1')).toHaveValue('El Sol es una estrella: revisado por el profesor');
  await page.screenshot({ path: testInfo.outputPath('chat-fullscreen.png'), animations: 'disabled' });
  await restore.click();
  await expect(chat.getByRole('button', { name: 'Pantalla completa' })).toHaveAttribute('aria-pressed', 'false');
  if (testInfo.project.name === 'desktop') expect((await chat.boundingBox())?.width).toBeLessThan(expanded!.width);
  await page.screenshot({ path: testInfo.outputPath('chat-proposal.png'), animations: 'disabled' });
  expect(await chat.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.locator('html').evaluate((element) => element.classList.remove('dark'));
  await page.screenshot({ path: testInfo.outputPath('chat-proposal-light.png'), animations: 'disabled' });
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Chat bot' })).toBeFocused();
  await page.getByRole('button', { name: 'Chat bot' }).click();
  await expect(chat.getByLabel('Afirmación propuesta 1')).toHaveValue('El Sol es una estrella: revisado por el profesor');
  await chat.getByRole('button', { name: 'Agregar al cuestionario' }).click();
  await expect(chat).not.toBeVisible();
  await expect(page.getByText('Las preguntas están guardadas en tu cuestionario.', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Chat bot' })).toBeFocused();
  await expect(savedQuestions).toHaveCount(before + 2);
  expect(await page.locator('html').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('chat-saved.png'), animations: 'disabled' });
  await page.getByRole('button', { name: 'Chat bot' }).click();
  await expect(chat.getByRole('button', { name: 'Agregar al cuestionario' })).toHaveCount(0);
  await chat.getByRole('button', { name: 'Pantalla completa' }).click();
  await page.keyboard.press('Escape');
  await expect(chat).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Chat bot' })).toBeFocused();
  await page.reload();
  await expect(page.getByText('El Sol es una estrella: revisado por el profesor', { exact: true })).toBeVisible();
});

test('propuesta plegable: seguir conversando y agregar dos países sin perder correcciones', async ({ page }, testInfo) => {
  await page.goto('/login');
  await page.getByLabel('Correo').fill('profe@profelink.test');
  await page.getByLabel('Contraseña', { exact: true }).fill('profelink123');
  await page.getByRole('button', { name: 'Entrar' }).click();
  await page.getByRole('link', { name: 'Paradigmas: repaso rápido', exact: true }).click();
  await page.getByRole('button', { name: 'Chat bot', exact: true }).click();
  const chat = page.getByRole('dialog', { name: 'Chat bot · ProfeLink' });
  const log = chat.getByRole('log');
  await chat.getByLabel('¿Qué preguntas necesitas?').fill('2 preguntas sobre países');
  await chat.getByRole('button', { name: 'Enviar' }).click();
  await expect(chat.getByRole('button', { name: 'Ver propuesta' })).toHaveAttribute('aria-expanded', 'false');
  await chat.getByRole('button', { name: 'Ver propuesta' }).click();
  await chat.getByLabel('Afirmación propuesta 1').fill('Costa Rica es un país de América Central: revisado.');
  expect((await log.boundingBox())!.height).toBeGreaterThan(80);
  await chat.getByRole('button', { name: 'Minimizar propuesta' }).click();
  await chat.getByRole('button', { name: 'Ver propuesta' }).focus();
  await page.keyboard.press('Enter');
  await expect(chat.getByLabel('Afirmación propuesta 1')).toHaveValue('Costa Rica es un país de América Central: revisado.');
  await chat.getByLabel('¿Qué preguntas necesitas?').fill('Agrega 2 países más');
  await chat.getByRole('button', { name: 'Enviar' }).click();
  await expect(log.getByText(/Modo simulado: añadí 2 ejemplos/)).toBeVisible();
  await expect(chat.getByRole('button', { name: 'Ver propuesta' })).toHaveAttribute('aria-expanded', 'false');
  await expect(chat.getByLabel('Afirmación propuesta 1')).not.toBeVisible();
  await expect(chat.getByText('4/4 elegidas', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('chat-collapsed-conversation.png'), animations: 'disabled' });
  await chat.getByRole('button', { name: 'Ver propuesta' }).click();
  await expect(chat.getByLabel('Afirmación propuesta 1')).toHaveValue('Costa Rica es un país de América Central: revisado.');
  await expect(chat.getByLabel('Afirmación propuesta 4')).toHaveValue(/Ejemplo simulado 4/);
  expect((await log.boundingBox())!.height).toBeGreaterThan(80);
  expect(await chat.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  await expect(log.getByText(/Modo simulado: añadí 2 ejemplos/)).toBeInViewport();
  await page.screenshot({ path: testInfo.outputPath('chat-expanded-proposal.png'), animations: 'disabled' });
  await chat.getByRole('button', { name: 'Cerrar chat' }).click();
  await expect(page.locator('section[aria-labelledby="questions-title"] > ol > li')).toHaveCount(3);
});
